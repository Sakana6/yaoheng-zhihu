import assert from 'node:assert/strict';
import path from 'node:path';
import {createServer} from 'vite';
const root=path.resolve('apps/mobile-app');
const server=await createServer({root,configFile:path.join(root,'vite.config.ts'),optimizeDeps:{noDiscovery:true,include:[]},server:{middlewareMode:true,watch:null,hmr:false}});
const originalFetch=globalThis.fetch;
try {
  const shared=name=>server.ssrLoadModule('/@fs/'+path.resolve('packages/frontend',name).replaceAll('\\','/'));
  const identity=await shared('session.ts'), {useManagementApi}=await shared('management-api.ts');
  identity.session.value={token:'synthetic',userId:1,role:'CAREGIVER'};
  identity.patients.value=[{id:42,name:'a'},{id:73,name:'b'}];identity.selectPatient(42);
  const api=useManagementApi(), calls=[];
  const {formatPatientAge}=await server.ssrLoadModule('/src/lib/format.ts');
  assert.equal(formatPatientAge('1948-10-01','2026-09-30'),'77 岁');
  assert.equal(formatPatientAge('1948-09-30','2026-09-30'),'78 岁');
  for(const birth of [null,'2026-02-30','2027-01-01','bad'])assert.equal(formatPatientAge(birth,'2026-09-30'),'年龄未提供');
  globalThis.fetch=async(url)=>{assert.match(url,/patients\/42\/profile$/);return Response.json({code:0,data:{id:42,birthday:'1948-09-30'}});};
  assert.equal((await api.profile()).birthday,'1948-09-30');
  const draft={genericName:'合成药',dose:'1片',frequency:'QD',administrationTime:'AFTER_BREAKFAST',startDate:'2026-09-29',endDate:null,status:'ACTIVE'};
  globalThis.fetch=async(url,init)=>{calls.push({url,init});throw Error('network unavailable');};
  await assert.rejects(api.saveMedication(null,draft),/network/);
  assert.equal(api.busy.value,false);
  globalThis.fetch=async(url,init)=>{calls.push({url,init});return new Response(JSON.stringify({code:0,data:{id:9,version:1}}));};
  await api.saveMedication(null,draft);
  assert.equal(calls[0].init.headers.get('Idempotency-Key'),calls[1].init.headers.get('Idempotency-Key'));
  assert.match(calls[1].url,/patients\/42\/medications$/);
  assert.equal(calls[1].init.headers.get('Authorization'),'Bearer synthetic');
  await api.saveMedication(9,{...draft,expectedVersion:1,status:'STOPPED'});
  assert.equal(calls[2].init.method,'PATCH');
  assert.equal(JSON.parse(calls[2].init.body).expectedVersion,1);
  assert.notEqual(calls[1].init.headers.get('Idempotency-Key'),calls[2].init.headers.get('Idempotency-Key'));
  let release;
  globalThis.fetch=()=>new Promise(r=>{release=r;});
  const pending=api.savePlan(null,{title:'合成提醒',frequency:'DAILY',medicationIds:[9]});
  await assert.rejects(api.savePlan(null,{}),/正在保存/);
  identity.selectPatient(73);
  release(new Response(JSON.stringify({code:0,data:{planId:'stale'}})));
  await assert.rejects(pending,/会话已改变/);
  await assert.rejects(api.plans(),/患者或会话/);
  const next=useManagementApi();let page=0;
  globalThis.fetch=async(url)=>{assert.match(url,/patients\/73/);page++;return new Response(JSON.stringify({code:0,data:{items:[{planId:String(page)}],nextCursor:page===1?'next':null}}));};
  assert.equal((await next.plans()).length,2);
  console.log('PASS management commands: patient binding, pagination, version, retry idempotency, busy guard and stale-session rejection');
} finally {globalThis.fetch=originalFetch;await server.close();}
