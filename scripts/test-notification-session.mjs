import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import { ref } from 'vue';
const identity={selectedPatient:ref({id:1}),sessionEpoch:ref(1),session:ref({role:'CAREGIVER'})};
const timers=new Map(),pending=[],scheduled=[];let nextTimer=0,clears=0,permission=true;
const module={exports:{}};
const code=ts.transpileModule(fs.readFileSync('packages/frontend/notification-session.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
vm.runInNewContext(code,{module,exports:module.exports,document:{visibilityState:'visible'},setInterval(fn){timers.set(++nextTimer,fn);return nextTimer;},clearInterval(id){timers.delete(id);},require(name){
  if(name==='vue')return {ref};
  if(name==='./session')return {...identity,backendRequest:path=>new Promise(resolve=>pending.push({path,resolve}))};
  if(name==='./care')return {careItems:(api,path)=>api(path)};
  if(name==='./notifications')return {notificationPermission:async()=>permission,notificationQueue:{stop:async()=>{clears++;},sync:async(items,enabled)=>{scheduled.push({items,enabled});}}};
  throw Error(name);
}});
const api=module.exports,flush=()=>new Promise(resolve=>setImmediate(resolve));
const stopA=api.startReminderNotifications();await flush();assert.equal(timers.size,1);
const reconcile=api.refreshReminderNotifications();await flush();assert.equal(timers.size,1,'page refresh cannot add another owner');
pending[1].resolve([{occurrenceId:'new'}]);await reconcile;
pending[0].resolve([{occurrenceId:'old'}]);await flush();
assert.equal(scheduled.length,1);assert.equal(scheduled[0].items[0].occurrenceId,'new');
const late=api.refreshReminderNotifications();await flush();stopA();identity.sessionEpoch.value++;identity.selectedPatient.value={id:2};
const stopB=api.startReminderNotifications();await flush();
pending[2].resolve([{occurrenceId:'patient1'}]);await late;
pending[3].resolve([{occurrenceId:'patient2'}]);await flush();
assert.equal(scheduled.length,2);assert.equal(scheduled[1].items[0].occurrenceId,'patient2');
assert.equal(timers.size,1);permission=false;await api.enableReminderNotifications();
assert.equal(api.remindersAllowed.value,false);assert.equal(scheduled.at(-1).enabled,false);
stopB();identity.session.value=null;identity.selectedPatient.value=null;identity.sessionEpoch.value++;
const stopNone=api.startReminderNotifications();assert.equal(timers.size,0);stopNone();assert.ok(clears>=4);
console.log('PASS notification session: one timer, route reconciliation, latest request wins, old patient cannot schedule, denial and logout cleanup');
