import assert from 'node:assert/strict';
import path from 'node:path';
import { createServer } from 'vite';

const root=path.resolve('apps/mobile-app');
const server=await createServer({root,configFile:path.join(root,'vite.config.ts'),optimizeDeps:{noDiscovery:true,include:[]},server:{middlewareMode:true,watch:null,hmr:false},logLevel:'error'});
const originalFetch=globalThis.fetch;
const response=(data,status=200,message='OK')=>new Response(JSON.stringify({code:status===200?0:status,message,data}),{status});
try {
  const shared=name=>server.ssrLoadModule('/@fs/'+path.resolve('packages/frontend',name).replaceAll('\\','/'));
  const identity=await shared('session.ts'),{useFeedbackDraft:makeFeedbackDraft}=await shared('feedback-draft.ts'),{useHomeCare}=await shared('home-care.ts');
  // This suite locks the legacy feature-disabled behavior; M12 has a separate enabled suite.
  const useFeedbackDraft=props=>makeFeedbackDraft({...props,raEnabled:false});
  identity.session.value={token:'synthetic',userId:1,role:'CAREGIVER'};
  identity.patients.value=[{id:42,name:'a'},{id:73,name:'b'}];identity.selectPatient(42);
  const occurrence={occurrenceId:'instance-a',version:4,planId:'plan-a',planVersion:2,title:'合成多药提醒',plannedAt:'2026-09-29T23:59:00+08:00',executionStatus:'PENDING',displayStatus:'PENDING',medications:[{medicationId:1,genericName:'合成甲'},{medicationId:2,genericName:'合成乙'}]};
  const draft=useFeedbackDraft({occurrence,medications:[]}),calls=[];
  assert.equal(draft.facts.value.medications.length,2);
  assert.ok(draft.facts.value.medications.every(m=>m.executionType==='UNKNOWN'));
  draft.rawText.value='合成原文：甲已服，乙未确认';draft.reviewed.value=true;
  draft.facts.value.medications[0].executionType='TAKEN';
  globalThis.fetch=async(url,init)=>{calls.push({url,init});throw Error('offline');};
  assert.equal(await draft.save(),undefined);
  assert.match(draft.error.value,/草稿已保留/);assert.equal(draft.rawText.value,'合成原文：甲已服，乙未确认');
  assert.equal(draft.busy.value,false);
  globalThis.fetch=async(url,init)=>{calls.push({url,init});return response({recordId:'record-a',version:1,analysisTask:{status:'PENDING'}});};
  assert.equal((await draft.save()).recordId,'record-a');
  assert.equal(calls[0].init.headers.get('Idempotency-Key'),calls[1].init.headers.get('Idempotency-Key'));
  const body=JSON.parse(calls[1].init.body);
  assert.equal(body.occurrenceId,'instance-a');assert.equal(body.expectedVersion,4);
  assert.equal(body.source,'REMINDER');assert.equal(body.confirmedFacts.explicitNoSymptoms,null);
  assert.deepEqual(body.confirmedFacts.medications.map(m=>m.executionType),['TAKEN','UNKNOWN']);
  assert.match(body.confirmedFacts.medications[0].occurredAt,/\+08:00$/);
  assert.equal(draft.facts.value.medications[0].occurredAt.includes('+08:00'),false,'saving must not mutate editable local times');
  draft.symptomState.value='none';await draft.save();
  assert.equal(JSON.parse(calls[2].init.body).confirmedFacts.explicitNoSymptoms,true);
  assert.notEqual(calls[1].init.headers.get('Idempotency-Key'),calls[2].init.headers.get('Idempotency-Key'));
  globalThis.fetch=async()=>response(null,409,'VERSION_CONFLICT');
  assert.equal(await draft.save(),undefined);assert.match(draft.error.value,/VERSION_CONFLICT/);
  assert.equal(draft.rawText.value,body.rawText);
  // Revision and follow-up retain their own evidence versions and timestamps.
  const priorFacts={...body.confirmedFacts,glucose:[{value:5.6,unit:'mmol/L',occurredAt:'2026-09-28T16:05:00Z'}]};
  const revision=useFeedbackDraft({record:{recordId:'r',version:3,rawText:'原文',occurredAt:'2026-09-28T16:00:00Z',source:'MANUAL',confirmedFacts:priorFacts},medications:[]});
  revision.reason.value='补充说明';revision.reviewed.value=true;
  globalThis.fetch=async(url,init)=>{assert.match(url,/feedback-records\/r\/revisions$/);const b=JSON.parse(init.body);assert.equal(b.expectedVersion,3);assert.equal(b.changeReason,'补充说明');assert.equal(Date.parse(b.confirmedFacts.glucose[0].occurredAt),Date.parse(priorFacts.glucose[0].occurredAt));return response({recordId:'r'});};
  await revision.save();
  const follow=useFeedbackDraft({followUp:{followUpId:'follow',version:7},medications:[]});
  globalThis.fetch=async(_,init)=>{const b=JSON.parse(init.body);assert.equal(b.followUpId,'follow');assert.equal(b.expectedFollowUpVersion,7);return response({});};await follow.save();
  const home=useHomeCare();
  globalThis.fetch=async url=>url.includes('/analysis/')?response(null,503,'AI_OFFLINE'):url.includes('/medications')?response({medications:[]}):response({items:[occurrence],nextCursor:null});
  await home.load();assert.equal(home.occurrences.value[0].occurrenceId,'instance-a');assert.match(home.analysisError.value,/AI_OFFLINE/);assert.match(home.summary.value,/不能据此判断风险正常/);
  const snapshot={runId:'run',snapshotId:'snap',inputRevision:1,risk:null,jointEvents:[]};
  globalThis.fetch=async url=>response(url.includes('/analysis/')?{snapshot,pendingTask:{status:'PENDING'},inputRevision:2}:url.includes('/medications')?{medications:[]}:{items:[occurrence],nextCursor:null});
  await home.load();assert.match(home.summary.value,/资料不足/);assert.equal(home.latest.value.snapshot.runId,'run');
  const requests=[];globalThis.fetch=(url)=>new Promise(resolve=>requests.push({url,resolve}));
  const oldLoad=home.load(),newLoad=home.load();
  for(const r of requests.slice(4))r.resolve(response(r.url.includes('/analysis/')?{snapshot:{...snapshot,runId:'new'},inputRevision:3}:r.url.includes('/medications')?{medications:[]}:{items:[],nextCursor:null}));
  await newLoad;
  for(const r of requests.slice(0,4))r.resolve(response(r.url.includes('/analysis/')?{snapshot}:r.url.includes('/medications')?{medications:[]}:{items:[occurrence],nextCursor:null}));
  await oldLoad;assert.equal(home.latest.value.snapshot.runId,'new');assert.equal(home.occurrences.value.length,0);
  const skips=[];globalThis.fetch=async(url,init)=>{skips.push({url,init});throw Error('offline');};
  assert.equal(await home.skip(occurrence,'合成原因'),false);
  globalThis.fetch=async(url,init)=>{skips.push({url,init});return response({});};
  assert.equal(await home.skip(occurrence,'合成原因'),true);
  assert.equal(skips[0].init.headers.get('Idempotency-Key'),skips[1].init.headers.get('Idempotency-Key'));
  await home.skip({...occurrence,occurrenceId:'other'},'合成原因');
  assert.notEqual(skips[1].init.headers.get('Idempotency-Key'),skips[2].init.headers.get('Idempotency-Key'));
  let release;globalThis.fetch=()=>new Promise(resolve=>{release=resolve;});
  const sending=draft.save();assert.equal(await draft.save(),undefined,'double submission is ignored');
  identity.selectPatient(73);release(response({recordId:'stale'}));
  assert.equal(await sending,undefined);assert.match(draft.error.value,/会话已改变/);
  let fetched=false;globalThis.fetch=async()=>{fetched=true;return response({});};
  await draft.save();assert.equal(fetched,false,'old draft cannot submit under another patient');
  home.dispose();
  fetched=false;
  await home.load();
  assert.equal(fetched,false,'disposed Home must ignore refresh without sending requests');
  assert.equal(home.loading.value,false,'disposed Home must not enter loading state');
  console.log('PASS original Home: real instances, AI failure isolation, missing vs normal, refresh races, multi-drug evidence, retry idempotency, revision times, follow-up version, conflict draft, busy and session isolation');
} finally {globalThis.fetch=originalFetch;await server.close();}
